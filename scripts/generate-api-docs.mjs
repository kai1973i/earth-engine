#!/usr/bin/env node
/**
 * Generates docs/reference/plugin-api.md from the TypeScript declarations in
 * packages/plugin-api. Uses only the TypeScript compiler that the workspace
 * already installs, so the reference always matches the types.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import ts from "typescript";

const ENTRY = "packages/plugin-api/src/index.ts";
const OUT = "docs/reference/plugin-api.md";

const source = ts.createSourceFile(ENTRY, readFileSync(ENTRY, "utf8"), ts.ScriptTarget.Latest, true);

const interfaces = [];
const aliases = [];
const constants = [];
const functions = [];

function description(node) {
  return ts
    .getJSDocCommentsAndTags(node)
    .map((entry) => (typeof entry.comment === "string" ? entry.comment : ""))
    .filter(Boolean)
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}

function isExported(node) {
  return Boolean(node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword));
}

for (const statement of source.statements) {
  if (!isExported(statement)) continue;

  if (ts.isInterfaceDeclaration(statement)) {
    const members = statement.members.map((member) => member.getText(source).replace(/\s+/g, " ").trim());
    interfaces.push({
      name: statement.name.text,
      description: description(statement),
      heritage: (statement.heritageClauses ?? [])
        .map((clause) => clause.getText(source))
        .join(" "),
      members,
    });
  } else if (ts.isTypeAliasDeclaration(statement)) {
    aliases.push({
      name: statement.name.text,
      description: description(statement),
      text: statement.type.getText(source),
    });
  } else if (ts.isFunctionDeclaration(statement) && statement.name) {
    functions.push({
      name: statement.name.text,
      description: description(statement),
      text: statement.getText(source),
    });
  } else if (ts.isVariableStatement(statement)) {
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name)) continue;
      constants.push({
        name: declaration.name.text,
        description: description(statement),
        text: declaration.getText(source),
      });
    }
  }
}

const lines = [
  "# Plugin API reference",
  "",
  "> Generated from `packages/plugin-api/src/index.ts` with `pnpm docs:api`.",
  "> Do not edit this file by hand; change the types and regenerate.",
  "",
  `The contract contains ${interfaces.length} interfaces, ${aliases.length} type aliases, ${constants.length} constants and ${functions.length} functions.`,
  "",
  "## Interfaces",
  "",
];

for (const entry of interfaces) {
  lines.push(`### \`${entry.name}\``, "");
  if (entry.description) lines.push(entry.description, "");
  if (entry.heritage) lines.push(`Extends ${entry.heritage}.`, "");
  lines.push("```ts", `interface ${entry.name} {`);
  for (const member of entry.members) lines.push(`  ${member}`);
  lines.push("}", "```", "");
}

lines.push("## Type aliases", "");
for (const entry of aliases) {
  lines.push(`### \`${entry.name}\``, "");
  if (entry.description) lines.push(entry.description, "");
  lines.push("```ts", `type ${entry.name} = ${entry.text};`, "```", "");
}

if (constants.length > 0) {
  lines.push("## Constants", "");
  for (const entry of constants) {
    if (entry.description) lines.push(entry.description, "");
    lines.push("```ts", `${entry.text};`, "```", "");
  }
}

if (functions.length > 0) {
  lines.push("## Functions", "");
  for (const entry of functions) {
    if (entry.description) lines.push(entry.description, "");
    lines.push("```ts", entry.text, "```", "");
  }
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${lines.join("\n")}\n`, "utf8");
console.log(`Wrote ${OUT} (${interfaces.length} interfaces, ${aliases.length} aliases).`);
